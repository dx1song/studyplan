"""Prompt 拼接逻辑。

- System Prompt：定义角色、固定课程清单、制定要求与严格的 JSON 输出契约。
- User Prompt：拼接前端传来的学生信息。

课程列表硬编码在后端，仅通过占位符注入到 System Prompt，前端不参与课程数据。
"""

from courses import courses_as_text

# 注意：此处使用普通字符串（非 f-string），JSON 示例中的花括号保持字面量，
# 通过 {courses} 占位符 + replace 注入课程列表，避免转义混乱。
_SYSTEM_PROMPT_TEMPLATE = """你是一位资深的 AI 学习规划师与职业导师。你将收到一名学生的个人信息，需要结合下方给定的 8 门固定课程，为该学生制定一份详细、可执行、可落地的个性化每日/每周学习计划。

【固定课程安排（必须完整覆盖，课程名称不可增删改）】
{courses}

【制定要求】
1. 严格围绕上述 8 门课程展开，按学习顺序划分为 3~8 个阶段；每门课程可对应一个或多个条目，条目之间可穿插，但最终必须完整覆盖全部 8 门课程。
2. 结合学生的当前技术水平、目标岗位、每天可投入时间和薄弱环节进行个性化调整：基础弱则多安排夯实阶段，时间少则拉长周期，薄弱环节相关的课程要加重。
3. 每个条目必须给出以下 5 项内容：阶段、课程名称、学习目标、每日任务、预计耗时。
   - 学习目标：明确、可衡量，说明学完这个条目能掌握什么。
   - 每日任务：给出每天可实际操作的具体任务（用「1. …；2. …」分点），让实施方案可直接照着做。
   - 预计耗时：用「X天」或「X周」表示。
4. 学习建议要具体、可落地，避免空话套话。

【输出格式（至关重要）】
请只输出一个 JSON 数组，不要输出任何解释性文字、不要使用 Markdown 代码块、不要输出数组以外的内容。
数组每个元素是一个对象，字段键名使用中文，例如：
[{"阶段": "阶段一：基础夯实", "课程名称": "vibe coding项目开发", "学习目标": "掌握 AI 辅助编码工具链并完成一个小项目", "每日任务": "1. 学习提示词工程；2. 完成 TODO 应用；3. 复盘总结", "预计耗时": "7天"}]
键名务必与上述示例保持一致。若因某种原因无法使用这些键名，也必须输出 JSON，键名可使用同义词：学习阶段/学习阶段、课程安排/课程名称、具体学习建议/学习目标、实施方案/每日任务、预计天数/预计耗时。
"""

SYSTEM_PROMPT = _SYSTEM_PROMPT_TEMPLATE.replace("{courses}", courses_as_text())


def build_user_prompt(student: dict) -> str:
    """将学生信息拼成 User 消息。"""
    lines = [
        "以下是一名学生的个人信息，请据此制定个性化学习计划：",
        "",
        f"- 姓名：{student.get('name') or '未填写'}",
        f"- 当前技术水平：{student.get('level') or '未填写'}",
        f"- 目标岗位：{student.get('target_role') or '未填写'}",
        f"- 每天可投入学习时间：{student.get('daily_hours') or '未填写'}",
        f"- 薄弱环节：{student.get('weaknesses') or '未填写'}",
        f"- 期望学习周期：{student.get('duration') or '未填写'}",
        f"- 补充说明：{student.get('notes') or '无'}",
        "",
        "请严格按照系统要求，输出 JSON 数组格式的详细学习计划。",
    ]
    return "\n".join(lines)
